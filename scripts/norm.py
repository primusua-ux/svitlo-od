"""Спільна нормалізація назв населених пунктів, вулиць і номерів будинків."""
import re

# ---------- нормалізація ----------
LAT2CYR = str.maketrans("ABCEHIKMOPTXaceiopxy", "АВСЕНІКМОРТХасеіорху")
TYPES = [
    ("prov", r"провулок|пров|пер|переулок|пр-к|прк"),
    ("prosp", r"проспект|просп|пр-т"),
    ("pl", r"площа|пл|майдан|м-н"),
    ("blv", r"бульвар|б-р|бул|б"),
    ("shose", r"шосе"),
    ("proizd", r"проїзд|пр-д"),
    ("uzviz", r"узвіз"),
    ("tupyk", r"тупик|туп"),
    ("nab", r"набережна|наб"),
    ("vul", r"вулиця|вул|ул|улица"),
]
TYPE_RE = [(t, re.compile(r"(?<![\w-])(?:%s)(?:\.|(?![\w-]))" % p, re.I)) for t, p in TYPES]

def street_key(s):
    """-> (тип, нормалізована назва з відсортованими словами)"""
    s = s.translate(LAT2CYR).lower().replace("ё", "е")
    s = re.sub(r"[ʼ'’`\"«»]", "", s)
    s = re.sub(r"(\d+)\s*-?\s*(?:й|ий|ій|я|а|го|ша|га|тя|та|ти|ма|ва|ої|ї|ого|ше|ге|те)(?![а-яіїєґ])", r"\1 ", s)
    typ = None
    for t, rx in TYPE_RE:
        if rx.search(s):
            s = rx.sub(" ", s)
            if typ is None or typ == "vul": typ = t
    s = re.sub(r"(?<![\w-])(?:мікрорайон|мкрн|мкр-н|мкр|масив|квартал|кв-л|урочище|ур|територія|містечко)(?:\.|(?![\w-]))", " ", s)
    s = re.sub(r"[.,;()№]", " ", s)
    toks = [t for t in s.replace("-", " ").split() if len(t) > 1 or t.isdigit()]
    return typ or "vul", " ".join(sorted(toks))

def house_key(h):
    h = h.translate(LAT2CYR).upper()
    h = re.sub(r"[\s]", "", h)
    h = re.sub(r"[,;]?(?:КОРП(?:УС)?\.?|К\.?)(?=\d)", "/", h)      # 12 корп.2, 12к2 -> 12/2
    h = re.sub(r"/+", "/", h)
    h = re.sub(r"^(\d+)[/-]([А-ЯІЇЄҐ])$", r"\1\2", h)             # 12-А, 12/А -> 12А
    return h

def place_key(s):
    s = re.sub(r"^(місто|м\.|село|с\.|селище|смт\.?|с/рада|хутір)\s*", "", s.strip(), flags=re.I)
    s = s.lower().replace("ё", "е")
    return re.sub(r"[ʼ'’`\"\s-]", "", s)


# ---------- різні написання однієї назви ----------
def fold(s):
    """Назва без різниць у написанні, які не змінюють саму назву: є/е, и/і/ї, подвоєні приголосні,
    м'який знак, -ів-/-ов-, -піль-/-поль-, -зьк-/-зськ-, закінчення (Тираспольська / Тираспольське)."""
    s = s.replace("ё", "е").replace("є", "е").replace("э", "е").replace("ї", "і").replace("и", "і").replace("ы", "і")
    s = s.replace("ь", "").replace("ъ", "").replace("ґ", "г")
    s = re.sub(r"([бвгджзклмнпрстфхцчшщ])\1", r"\1", s)
    s = s.replace("зск", "зк").replace("івск", "овск").replace("піл", "пол")
    s = re.sub(r"ів\b", "ов", s)
    s = re.sub(r"(?<=[^\W\d]{4})(?:ая|[аоеяі])\b", "", s)
    return s

def fold_key(k):
    return k[0], " ".join(sorted(fold(k[1]).split()))

